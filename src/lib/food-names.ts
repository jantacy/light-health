// 食物名称归一化：同一种食物的不同叫法（西红柿/番茄、土豆/马铃薯…）得到同一个库键。
// 服务端食物库和前端本地缓存共用。只收录意思完全相同的叫法，宁可漏掉也不要把两种食物并成一种。

// 每组第一个是标准叫法。名称里出现组内任一叫法，都换成标准叫法（长的优先匹配）。
const SYNONYMS: string[][] = [
  ["番茄", "西红柿"],
  ["土豆", "马铃薯", "洋芋"],
  ["蛋", "鸡蛋"],
  ["米饭", "白米饭", "大米饭", "白饭"],
  ["白粥", "大米粥", "稀饭"],
  ["红薯", "甘薯", "地瓜", "番薯", "山芋"],
  ["菜花", "花菜", "花椰菜"],
  ["西兰花", "西蓝花", "绿菜花"],
  ["卷心菜", "包菜", "圆白菜", "洋白菜", "甘蓝"],
  ["空心菜", "蕹菜"],
  ["香菜", "芫荽"],
  ["香油", "芝麻油"],
  ["酸奶", "酸牛奶"],
  ["纯牛奶", "牛奶", "鲜牛奶"],
  ["鸡胸肉", "鸡胸脯肉", "鸡胸"],
  ["里脊肉", "里脊"],
  ["玉米", "苞米"],
  ["黄瓜", "胡瓜"],
  ["青椒", "柿子椒"],
  ["豆腐脑", "豆花"],
  ["小白菜", "青菜"],
  ["荷包蛋", "煎蛋"],
  ["水煮蛋", "白煮蛋", "煮蛋"]
];

const canonical = new Map(SYNONYMS.flatMap(([main, ...rest]) => [[main, main], ...rest.map((s) => [s, main] as [string, string])]));
const pattern = new RegExp([...canonical.keys()].sort((a, b) => b.length - a.length).join("|"), "g");
// 括号里只是份量/规格（450ml、约200克、2个）时去掉；“少油”“微糖”这类会改变营养的保留。
const amount = /\([^()]*\d[^()]*(ml|毫升|l|升|g|克|kg|千克|斤|两|个|只|片|碗|杯|份|块|根|颗|勺|盒|瓶|袋)[^()]*\)/g;

export function foodKey(name: string): string {
  return name
    .replace(/\s+/g, "").toLowerCase()
    .replace(/[（［【]/g, "(").replace(/[）］】]/g, ")")
    .replace(amount, "")
    .replace(pattern, (s) => canonical.get(s)!)
    .replace(pattern, (s) => canonical.get(s)!); // 第二遍：白煮鸡蛋 → 白煮蛋 → 水煮蛋
}
